#!/usr/bin/env python3
"""Build a hub SOP page from its markdown source so the two never drift.

Usage:
  python3 scripts/build-sop-page.py <source.md> <pages/out.html> "<subtitle>"

The markdown file (kept in SharePoint) is the source of truth. Edit it, then
re-run this script. Conventions the script styles:
  - "**Done when:** ..." paragraphs become a green done-when box.
  - Blockquotes become "say this" script boxes.
  - The section whose heading starts with "Builder appendix" gets its own panel.
  - Anything between <!-- internal --> and <!-- /internal --> stays in the
    SharePoint file only. This hub is a PUBLIC GitHub Pages site.

Safety check: the build fails if the public page would contain the name of any
folder under the BPP workspace's "2. Client Operations" (active or Archived).
"""
import html
import os
import re
import sys
from datetime import date

import markdown

src, out, subtitle = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src, encoding="utf-8").read()
text = re.sub(r"<!-- internal -->.*?<!-- /internal -->\s*", "", text, flags=re.S)

clients_dir = os.path.expanduser("~/AIOS/BPP Operations - BPP Workspace/2. Client Operations")
if os.path.isdir(clients_dir):
    names = [n for n in os.listdir(clients_dir) if not n.startswith(("_", "."))]
    archived = os.path.join(clients_dir, "Archived")
    if os.path.isdir(archived):
        names += os.listdir(archived)
    names = {
        part.strip()
        for n in names if n != "Archived" and not n.startswith(".")
        for part in re.split(r" - | and ", n)
    }
    leaks = sorted(n for n in names if len(n) > 2 and re.search(r"\b" + re.escape(n) + r"\b", text))
    if leaks:
        sys.exit(f"REFUSING TO BUILD: client names in public content: {', '.join(leaks)}")
else:
    print("warning: client folder list not found; client-name check skipped")

# Title = first H1; the italic line right under it is the version/owner meta.
m = re.match(r"#\s+(.+)\n+(\*[^\n]+\*)\n", text)
title = m.group(1).strip() if m else "SOP"
meta_md = m.group(2) if m else ""
body_md = text[m.end():] if m else text

def normalize_lists(src_md):
    """Python-Markdown needs a blank line before a list and 4-space nesting;
    SharePoint/GitHub markdown doesn't. Rewrite list indentation so both agree."""
    out, stack, prev_blank, in_list = [], [], True, False
    for line in src_md.split("\n"):
        m = re.match(r"^( *)([-*]|\d+\.) ", line)
        if m:
            ind = len(m.group(1))
            while stack and ind < stack[-1]:
                stack.pop()
            if not stack or ind > stack[-1]:
                stack.append(ind)
            if not in_list and not prev_blank:
                out.append("")
            out.append("    " * (len(stack) - 1) + line.lstrip())
            in_list, prev_blank = True, False
        elif not line.strip():
            out.append(line)
            prev_blank = True
        elif line.startswith(" ") and stack:
            out.append("    " * len(stack) + line.lstrip())
            prev_blank = False
        else:
            stack, in_list = [], False
            out.append(line)
            prev_blank = False
    return "\n".join(out)


body_md = normalize_lists(body_md)
md = markdown.Markdown(extensions=["tables", "sane_lists", "toc"], extension_configs={"toc": {"toc_depth": "2"}})
body = md.convert(body_md)
meta = markdown.markdown(meta_md)

body = re.sub(r"<p><strong>Done when:</strong>", '<p class="done"><strong>Done when:</strong>', body)
body = body.replace("<blockquote>", '<blockquote class="say">')
body = re.sub(r"<table>", '<div class="tbl"><table>', body)
body = body.replace("</table>", "</table></div>")

# Wrap the builder appendix (last H2 starting with "Builder appendix") in a panel.
bm = re.search(r'<h2 id="[^"]*">Builder appendix', body)
if bm:
    body = body[: bm.start()] + '<section class="builder">' + body[bm.start():] + "</section>"

toc_items = "".join(
    f'<li><a href="#{t["id"]}">{html.escape(t["name"])}</a></li>' for t in md.toc_tokens
)

page = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{html.escape(title)} · BPP Tools Hub</title>
<link href="https://fonts.googleapis.com/css2?family=Montserrat:wght@400;500;600;700;800&family=Poppins:wght@300;400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../css/styles.css">
<!-- Generated by scripts/build-sop-page.py from the SharePoint markdown. Edit the markdown, not this file. -->
<style>
  *, *::before, *::after {{ box-sizing: border-box; }}
  :root {{
    --navy: #044771; --navy-dark: #033359; --blue-mid: #3a6d8f;
    --gold: #F1BE5C; --gold-dark: #d4a43e; --bg: #edf1f5; --card: #ffffff;
    --line: #c8d3dc; --ink: #14222f; --gray: #333f4a; --green: #17653d;
  }}
  body {{ font-family: 'Poppins', sans-serif; background: var(--bg); color: var(--ink); }}
  .sop-hero {{ background: linear-gradient(135deg, var(--navy-dark), var(--navy)); color: #fff; padding: 32px 48px; }}
  .sop-hero h1 {{ font-family: 'Montserrat', sans-serif; font-size: 32px; font-weight: 800; margin: 0; line-height: 1.2; }}
  .sop-hero .sub {{ font-size: 17px; line-height: 1.5; opacity: .88; margin: 8px 0 0; max-width: 720px; }}
  .wrap {{ max-width: 820px; margin: 0 auto; padding: 24px 24px 64px; }}
  .back {{ display: inline-flex; align-items: center; min-height: 44px; font-size: 15px; font-weight: 600; color: var(--blue-mid); text-decoration: none; }}
  .back:hover {{ color: var(--navy); }}
  .meta {{ font-size: 14px; color: var(--gray); background: var(--card); border: 1px solid var(--line); border-radius: 10px; padding: 12px 16px; margin: 8px 0 18px; }}
  .meta p {{ margin: 0; font-size: 14px; line-height: 1.55; }}
  details.toc {{ background: var(--card); border: 1px solid var(--line); border-left: 5px solid var(--gold); border-radius: 10px; padding: 4px 18px; margin-bottom: 26px; }}
  details.toc summary {{ cursor: pointer; font-family: 'Montserrat', sans-serif; font-weight: 700; color: var(--navy); font-size: 16px; min-height: 44px; display: flex; align-items: center; }}
  details.toc ol {{ margin: 4px 0 14px; padding-left: 22px; columns: 2; column-gap: 28px; }}
  details.toc li {{ font-size: 15px; line-height: 1.5; margin: 0 0 6px; break-inside: avoid; }}
  details.toc a {{ color: var(--navy); text-decoration: none; display: inline-block; padding: 3px 0; }}
  details.toc a:hover {{ text-decoration: underline; }}
  .content {{ font-size: 17px; line-height: 1.62; color: var(--gray); }}
  .content h2 {{ font-family: 'Montserrat', sans-serif; font-size: 25px; font-weight: 800; color: var(--navy); margin: 40px 0 12px; padding-bottom: 8px; border-bottom: 3px solid var(--gold); line-height: 1.25; scroll-margin-top: 72px; }}
  .content h3 {{ font-family: 'Montserrat', sans-serif; font-size: 19px; font-weight: 700; color: var(--ink); margin: 24px 0 8px; }}
  .content p {{ margin: 0 0 14px; }}
  .content strong {{ color: var(--ink); }}
  .content ul, .content ol {{ margin: 0 0 16px; padding-left: 26px; }}
  .content li {{ margin: 0 0 8px; }}
  .content li > ul, .content li > ol {{ margin: 8px 0 4px; }}
  .content code {{ font-family: ui-monospace, Menlo, monospace; font-size: .86em; background: #eef2f6; border: 1px solid #dde5ec; border-radius: 4px; padding: 1px 5px; color: var(--navy); overflow-wrap: anywhere; }}
  .content a {{ color: var(--navy); }}
  .content hr {{ display: none; }}
  .content .done {{ background: #e9f6ee; border-left: 5px solid var(--green); border-radius: 8px; padding: 12px 16px; color: #14422a; }}
  .content .done strong {{ color: var(--green); }}
  .content blockquote.say {{ margin: 0 0 16px; background: #f3f7fb; border-left: 5px solid var(--navy); border-radius: 8px; padding: 12px 16px; }}
  .content blockquote.say p {{ margin: 0; font-style: italic; color: var(--ink); }}
  .content .tbl {{ overflow-x: auto; margin: 0 0 18px; }}
  .content table {{ width: 100%; border-collapse: collapse; background: var(--card); border: 1px solid var(--line); border-radius: 10px; font-size: 15.5px; line-height: 1.5; }}
  .content th {{ background: var(--navy); color: #fff; text-align: left; font-family: 'Montserrat', sans-serif; font-size: 14px; padding: 10px 12px; }}
  .content td {{ padding: 10px 12px; border-top: 1px solid #e3e9ef; vertical-align: top; }}
  .content tbody tr:nth-child(even) {{ background: #f7fafc; }}
  .builder {{ margin-top: 44px; background: #f6f3ea; border: 1px solid #e6d9b5; border-radius: 12px; padding: 4px 22px 18px; }}
  .builder h2 {{ border-bottom-color: var(--gold-dark); }}
  .sop-foot {{ background: var(--navy-dark); color: rgba(255,255,255,.7); font-size: 13px; padding: 18px 48px; }}
  @media (max-width: 640px) {{
    .sop-hero {{ padding: 24px 18px; }}
    .sop-hero h1 {{ font-size: 27px; }}
    .wrap {{ padding: 16px 16px 48px; }}
    details.toc ol {{ columns: 1; }}
    .content {{ font-size: 17px; }}
    .content h2 {{ font-size: 22px; }}
    .builder {{ padding: 4px 14px 14px; }}
    .sop-foot {{ padding: 16px 18px; }}
  }}
</style>
</head>
<body>
<div id="hub-nav"></div>

<header class="sop-hero">
  <h1>{html.escape(title)}</h1>
  <p class="sub">{html.escape(subtitle)}</p>
</header>

<main class="wrap">
  <a class="back" href="sops.html">&larr; All SOPs</a>
  <div class="meta">{meta}</div>
  <details class="toc" open>
    <summary>On this page</summary>
    <ol>{toc_items}</ol>
  </details>
  <article class="content">
{body}
  </article>
</main>

<footer class="sop-foot">Business Plans Plus · Internal SOP · Page built {date.today().isoformat()} from the SharePoint markdown file of the same name.</footer>

<script>if (window.innerWidth < 640) document.querySelector('details.toc').removeAttribute('open');</script>
<script src="../js/nav.js" data-page="sops"></script>
</body>
</html>
"""
open(out, "w", encoding="utf-8").write(page)
print(f"wrote {out}: {len(page):,} bytes, {len(md.toc_tokens)} sections")
